// Type Conversion


//String --> Number
let account_balance =  "100"
let num = Number(account_balance)

console.log(num)


//Boolean --> Number
let x = true
console.log(Number(x))


//Null --> Number
let a = null
console.log(Number(a))


//undefined --> Number
let x1;
console.log(Number(x1));


//Number --> String
let ab= 100
console.log(String(ab))


//Boolean --> String
let ax= true
console.log(String(ax))


//Null--> String
let ac= null
console.log(String(ac))


//Undefined--> String
let x2;
console.log(String(x2))


//String--> Boolean
let aa= "Hello"
console.log(Boolean(aa))

let bb= ""
console.log(Boolean(bb))


//String--> Bigint
let ad = "1000987659"
console.log(BigInt(ad))


//Boolean--> BigInt
let cc = true
console.log(BigInt(cc))